function glyphBytes(c) {
  const g = ART[c];
  if (!g) throw new Error('missing glyph ' + c);
  const out = [];
  for (let col = 0; col < 5; col++) {
    let b = 0;
    for (let row = 0; row < 7; row++) if (g[row][col] === '1') b |= 1 << row;
    out.push(b);
  }
  return out;
}

function fontBytes() {
  const out = [];
  for (const c of CHARS) out.push(...glyphBytes(c));
  return out;
}

function strIdx(s) {
  const out = [];
  for (const c of s) {
    const i = CHARS.indexOf(c);
    if (i < 0) throw new Error('char not in font: ' + c);
    out.push(i);
  }
  out.push(255);
  return out;
}

