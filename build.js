const PAYLOAD_DEST = 0x03000000;
const PAYLOAD_SRC = 0x08001000;
const ROM_SIZE = 0x40000;

function buildBoot(nWords) {
  const A = new Asm(0x080000C0);
  A.label('boot');
  A.ldrk('r0', PAYLOAD_SRC);
  A.ldrk('r1', PAYLOAD_DEST);
  A.ldrk('r2', nWords);
  A.label('bcopy');
  A.stm('ia', 'r0', ['r4', 'r5', 'r6', 'r7'], { wb: true, load: true });
  A.stm('ia', 'r1', ['r4', 'r5', 'r6', 'r7'], { wb: true });
  A.sub('r2', 'r2', 1, { s: true });
  A.b('bcopy', 'ne');
  A.ldrk('r0', PAYLOAD_DEST);
  A.mov('pc', 'r0');
  A.pool();
  return A.assemble().buf;
}

function makeRom(payload, title) {
  if (payload.length > 0x7000) throw new Error('payload too big for IWRAM: ' + payload.length);
  const words = Math.ceil(payload.length / 16);
  const padded = Buffer.alloc(words * 16, 0);
  Buffer.from(payload).copy(padded, 0);

  const header = Buffer.alloc(0xC0, 0);
  header.writeUInt32LE(0xEA00002E, 0);      // b 0x080000C0
  NINTENDO_LOGO.copy(header, 4);
  header.write((title || 'LIGHTS OUT').slice(0, 12).padEnd(12, ' '), 0xA0, 12, 'ascii');
  header.write('LOUT', 0xAC, 4, 'ascii');
  header.write('01', 0xB0, 2, 'ascii');
  header[0xB2] = 0x96;
  header[0xB3] = 0x00;
  header[0xB4] = 0x00;
  header[0xBC] = 0x00;
  let chk = 0;
  for (let i = 0xA0; i <= 0xBC; i++) chk -= header[i];
  header[0xBD] = (chk - 0x19) & 0xFF;

  const boot = Buffer.from(buildBoot(words));
  if (0xC0 + boot.length > 0x1000) throw new Error('boot too big');

  const rom = Buffer.alloc(ROM_SIZE, 0xFF);
  header.copy(rom, 0);
  boot.copy(rom, 0xC0);
  padded.copy(rom, 0x1000);
  return rom;
}

